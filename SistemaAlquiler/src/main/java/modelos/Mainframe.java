    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        try {
    String doc = txtClienteDoc.getText();
    String nombre = txtClienteNombre.getText();
    String placa = txtPlaca.getText();
    
    if (doc.isEmpty() || nombre.isEmpty() || placa.isEmpty() || txtDias.getText().isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor complete todos los campos.", "Campos vacíos", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    int dias = Integer.parseInt(txtDias.getText());

    // Creación de objetos a partir del código modelo
    Cliente cliente = new Cliente(doc, nombre, "N/A");
    Vehiculo moto = new Motocicleta(placa, "Yamaha", "2024");
    Alquiler nuevoAlquiler;
            nuevoAlquiler = new Alquiler(cliente, moto, dias);

    // Mostrar en el área de texto
    txtAreaResultado.append(nuevoAlquiler.toString() + "\n");

    // Limpiar campos
    txtClienteDoc.setText("");
    txtClienteNombre.setText("");
    txtPlaca.setText("");
    txtDias.setText("");

    javax.swing.JOptionPane.showMessageDialog(this, "¡Alquiler registrado con éxito!");

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un número válido para los días.", "Error de entrada", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnRegistrarActionPerformed

